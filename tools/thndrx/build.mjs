// Builds the ThndrX userscript: node tools/thndrx/build.mjs -> tools/thndrx/dist/thndrx-ict.user.js
// Each module runs in its own function scope inside a tiny registry (__m), so modules may reuse top-level names:
//   import { a, b as c } from './x.mjs'   ->  const { a, b: c } = __m['thndrx/x.mjs'];
//   export function f / export const x     ->  plain declarations, returned as the module's exports object.
// Anything the transform cannot resolve (node: built-ins, files outside the bundle, default/namespace imports,
// export lists, import.meta, dynamic import) fails the build.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const TOOLS = fileURLToPath(new URL('..', import.meta.url));
const OUT = fileURLToPath(new URL('./dist/thndrx-ict.user.js', import.meta.url));
const VERSION_FILE = fileURLToPath(new URL('./VERSION', import.meta.url));

// Dependency order (module ids are paths under tools/).
export const MODULES = [
  'backtest/ict-engine.mjs', 'thndrx/colors.mjs', 'thndrx/format.mjs', 'thndrx/inputs.mjs', 'thndrx/htf.mjs',
  'thndrx/panel.mjs', 'thndrx/render-plan.mjs', 'thndrx/painter.mjs', 'thndrx/chart-port.mjs', 'thndrx/ui.mjs', 'thndrx/main.mjs',
];

const IMPORT = /^import\s*\{([^}]*)\}\s*from\s*'([^']+)';?[ \t]*$/gm;
const EXPORT_DECL = /^export\s+((?:async\s+)?function\*?|const|let|var|class)\s+([A-Za-z_$][\w$]*)/gm;

// One module's source -> { code, exports, deps }. `known` is the set of module ids in the bundle.
export function transformModule(source, id, known) {
  const deps = [];
  let code = source.replace(/\r\n/g, '\n').replace(IMPORT, (_, names, spec) => {
    if (!spec.startsWith('.')) throw new Error(`${id}: cannot resolve import '${spec}' (not a bundled module)`);
    const dep = path.posix.normalize(path.posix.join(path.posix.dirname(id), spec));
    if (!known.has(dep)) throw new Error(`${id}: cannot resolve import '${spec}' (${dep} is not in the bundle)`);
    deps.push(dep);
    const list = names.split(',').map((n) => n.trim()).filter(Boolean).map((n) => {
      const m = /^([A-Za-z_$][\w$]*)(?:\s+as\s+([A-Za-z_$][\w$]*))?$/.exec(n);
      if (!m) throw new Error(`${id}: unsupported import name '${n}'`);
      return m[2] ? `${m[1]}: ${m[2]}` : m[1];
    });
    return `const { ${list.join(', ')} } = __m['${dep}'];`;
  });
  const leftover = /^\s*import\b.*$/m.exec(code);
  if (leftover) {
    const spec = /'([^']+)'/.exec(leftover[0]);
    if (spec && !spec[1].startsWith('.')) throw new Error(`${id}: cannot resolve import '${spec[1]}' (not a bundled module)`);
    throw new Error(`${id}: unsupported import form: ${leftover[0].trim()}`);
  }
  if (/\bimport\s*\(|\bimport\.meta\b/.test(code)) throw new Error(`${id}: unsupported dynamic import or import.meta`);

  const exports = [];
  code = code.replace(EXPORT_DECL, (_, kind, name) => { exports.push(name); return `${kind} ${name}`; });
  const left = /^\s*export\b.*$/m.exec(code);
  if (left) throw new Error(`${id}: unsupported export form: ${left[0].trim()}`);
  return { code, exports, deps };
}

export function buildBundle() {
  const version = fs.readFileSync(VERSION_FILE, 'utf8').trim();
  const known = new Set(MODULES), seen = new Set();
  const parts = [
    '// ==UserScript==',
    '// @name         ThndrX ICT + RSI/MA Confluence',
    `// @version      ${version}`,
    '// @description  The ICT + RSI/MA Confluence indicator drawn on the ThndrX chart (unsaved drawings, settings in localStorage).',
    '// @match        https://x.thndr.app/*',
    '// @grant        none',
    '// @run-at       document-idle',
    '// ==/UserScript==',
    '// Generated by tools/thndrx/build.mjs from tools/thndrx and tools/backtest/ict-engine.mjs. Do not edit by hand.',
    '(function () {',
    "'use strict';",
    'const __m = {};',
  ];
  for (const id of MODULES) {
    const { code, exports, deps } = transformModule(fs.readFileSync(path.join(TOOLS, id), 'utf8'), id, known);
    for (const d of deps) if (!seen.has(d)) throw new Error(`${id}: imports ${d}, which is not bundled before it`);
    seen.add(id);
    parts.push(`__m['${id}'] = (function () {`, "'use strict';", code.trimEnd(), `return { ${exports.join(', ')} };`, '})();');
  }
  if (!seen.has('thndrx/main.mjs')) throw new Error('main module missing');
  parts.push("const { start } = __m['thndrx/main.mjs'];", 'start();', '})();', '');
  return parts.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const js = buildBundle();
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, js);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${js.length} bytes)`);
}
